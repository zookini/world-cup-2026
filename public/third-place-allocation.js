const ALLOCATION_BY_GROUPS = new Map(
  ALLOCATION_ROWS.map((thirds) => [[...thirds].sort().join(""), thirds]),
);

// Given the eight groups whose third-placed teams qualified, return a map from
// each winner's group letter to the third-placed group it faces, per Annexe C.
// Returns null unless exactly eight groups are supplied and the combination is
// found (it always is for a real eight-team set).
export function thirdPlaceAllocation(qualifyingGroups) {
  const key = [...qualifyingGroups].map((g) => g.toUpperCase()).sort().join("");
  if (key.length !== 8) return null;
  const thirds = ALLOCATION_BY_GROUPS.get(key);
  if (!thirds) return null;
  const byWinner = new Map();
  WINNER_SLOTS.forEach((winner, i) => byWinner.set(winner, thirds[i]));
  return byWinner;
}
